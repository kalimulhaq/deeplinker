// Embeds the built runtime IIFE template into the generator as a TS module, so the generator stays a pure
// function with no file-system access at run time (the Phase 3 web generator imports it in a browser).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "packages/runtime/dist/deeplinker.iife.min.js");
const target = resolve(root, "packages/generator/src/runtime-template.generated.ts");

let template = "";
if (existsSync(source)) {
  template = readFileSync(source, "utf8");
} else {
  console.warn(
    `[embed-runtime] ${source} not found; embedding an empty template. Run \`pnpm --filter @deeplinker/runtime build\`.`,
  );
}

writeFileSync(
  target,
  `// Generated by scripts/embed-runtime.mjs. Do not edit.\nexport const RUNTIME_TEMPLATE: string = ${JSON.stringify(template)};\n`,
);
