import { describe, expect, it } from "vitest";
import { buildBundle, zipBundle, ZIP_FOLDER, type Bundle } from "../src/bundle";
import { EXAMPLE } from "../src/example";
import { toJsonText } from "../src/form";
import { asText, readZip } from "./zip-reader";

const ok = (bundle: Bundle) => {
  if (!bundle.ok) throw new Error(JSON.stringify(bundle));
  return bundle;
};
const example = toJsonText(EXAMPLE);

describe("buildBundle", () => {
  it("reports a JSON syntax error as such", () => {
    const bundle = buildBundle("{ nope");
    expect(bundle).toMatchObject({ ok: false, kind: "json" });
  });

  it("reports config problems with the path, the message and an example", () => {
    const bundle = buildBundle(JSON.stringify({ domains: ["https://example.com/"] }));
    expect(bundle.ok).toBe(false);
    if (bundle.ok || bundle.kind !== "config") throw new Error("expected config issues");
    expect(bundle.issues[0]).toMatchObject({ path: "domains[0]" });
    expect(bundle.issues[0]?.message).toContain("URL");
    expect(bundle.issues[0]?.example).toContain("example.com");
    expect(bundle.text).toContain("domains[0]");
  });

  it("asks for domains when there is nothing else", () => {
    const bundle = buildBundle("{}");
    expect(bundle.ok).toBe(false);
  });

  it("generates the files for a valid config, with where each one goes", () => {
    const bundle = ok(buildBundle(example));
    const paths = bundle.files.map((f) => f.path);
    expect(paths).toEqual(
      expect.arrayContaining([
        ".well-known/apple-app-site-association",
        ".well-known/assetlinks.json",
        "deeplinker.js",
        "snippet.html",
        "nginx-deeplinker.conf",
        "README-DEPLOY.md",
      ]),
    );
    expect(bundle.domains).toEqual(["example.com", "www.example.com"]);
    expect(bundle.host).toMatchObject({ id: "nginx", detected: false });
    expect(bundle.hash).toMatch(/^[0-9a-f]{14}$/);
    expect(bundle.destinations[".well-known/assetlinks.json"]).toContain(
      "https://example.com/.well-known/assetlinks.json",
    );
    expect(bundle.destinations["snippet.html"]).toContain("<head>");
    for (const path of paths) expect(bundle.destinations[path], path).toBeTruthy();
  });

  it("is deterministic", () => {
    expect(ok(buildBundle(example)).files).toEqual(ok(buildBundle(example)).files);
  });

  it("with hosting 'auto' and no project to look at, writes for plain static hosting", () => {
    const bundle = ok(buildBundle(JSON.stringify({ ...EXAMPLE, hosting: undefined })));
    expect(bundle.host.id).toBe("static");
  });

  it("merges the files you paste, and leaves a blank one alone", () => {
    const withApache = JSON.stringify({ ...EXAMPLE, hosting: "apache" });
    const mine = "RewriteEngine On\nRewriteRule ^old$ /new [R=301,L]\n";
    const merged = ok(buildBundle(withApache, { htaccess: mine, headers: "   \n" }));
    const htaccess = merged.files.find((f) => f.path === ".htaccess");
    expect(htaccess?.before).toBe(mine);
    expect(htaccess?.content.endsWith(mine)).toBe(true);
    expect(merged.files.some((f) => f.path === "_headers")).toBe(false);
  });

  it("carries the config's warnings", () => {
    const bundle = ok(
      buildBundle(
        JSON.stringify({ ...EXAMPLE, deferred: { enabled: true, storage: "sqlite" }, hosting: "vercel" }),
      ),
    );
    expect(bundle.warnings.join("\n")).toContain('"sqlite" does not work with the vercel endpoint');
  });
});

describe("zipBundle", () => {
  it("puts every file under deeplinker-dist/, in order, with the generated bytes", () => {
    const bundle = ok(buildBundle(example));
    const entries = readZip(zipBundle(bundle));
    expect(entries.map((e) => e.name)).toEqual(bundle.files.map((f) => `${ZIP_FOLDER}/${f.path}`));
    expect(entries.map(asText)).toEqual(bundle.files.map((f) => f.content));
  });
});
